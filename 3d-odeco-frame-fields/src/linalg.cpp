mat15 rotation_15d(double alpha, double beta, double gamma)
{

    const mat15 rot_x = rotation_x_15d(alpha);
    const mat15 rot_y = rotation_y_15d(beta);
    const mat15 rot_z = rotation_z_15d(gamma);

    const mat15 tmp = block_prod_mat(rot_x, rot_y);
    return block_prod_mat(tmp, rot_z);
}

mat15 rotation_15d(const vec3& theta)
{
    return rotation_15d(theta.x(), theta.y(), theta.z());
}

