mat3 rotation_x_3d(double alpha) {
    return mat3{
    {1, 0, 0},
        {0, cos(alpha), -sin(alpha)},
        {0, sin(alpha), cos(alpha)}
    };
}
mat3 rotation_y_3d(double beta){
    return mat3{
        {cos(beta), 0, sin(beta)},
        {0, 1, 0},
        {-sin(beta), 0, cos(beta)}
    };
}
mat3 rotation_z_3d(double gamma){
    return mat3{
        {cos(gamma), -sin(gamma), 0},
            {sin(gamma), cos(gamma), 0},
            {0, 0, 1}
    };
}


mat3 rotation_3d(double alpha, double beta, double gamma) {
    return rotation_x_3d(alpha) * rotation_y_3d(beta) * rotation_z_3d(gamma);
}

mat3 rotation_3d(const vec3& theta) {
    return rotation_3d(theta.x(), theta.y(), theta.z());
}

