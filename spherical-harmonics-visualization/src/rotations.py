def rotate_x_3(theta):
    return np.array([
        [1, 0, 0],
        [0, cos(theta), -sin(theta)],
        [0, sin(theta), cos(theta)]
    ])

def rotate_y_3(theta):
    return np.array([
        [cos(theta), 0, sin(theta)],
        [0, 1, 0],
        [-sin(theta), 0, cos(theta)]
    ])

def rotate_z_3(theta):
    return np.array([
        [cos(theta), -sin(theta), 0],
        [sin(theta), cos(theta), 0],
        [0, 0, 1]
    ])

def rotate_3(v, alpha, beta, gamma):
    return rotate_x_3(alpha) @ rotate_y_3(beta) @ rotate_z_3(gamma) @ v

